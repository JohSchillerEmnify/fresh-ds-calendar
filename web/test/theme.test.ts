import fs from 'node:fs';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { DEFAULT_SEED, applySeed, applyThemeMode } from '@/theme';
import { schemeVars, themeCss } from '@/theme/scheme';

const TOKENS = path.join(import.meta.dirname, '../src/theme/tokens.css');
const HEADER = '/* GENERATED by `pnpm -F @calendar/web tokens` from DEFAULT_SEED. Do not edit by hand. */\n';

describe('M3 theme', () => {
  afterEach(() => {
    document.getElementById('m3-dynamic-theme')?.remove();
    document.documentElement.removeAttribute('data-theme');
  });

  it('generates all core M3 color roles for light and dark', () => {
    for (const dark of [false, true]) {
      const v = schemeVars('#6750a4', dark);
      for (const role of ['primary', 'on-primary', 'primary-container', 'surface', 'surface-container-high', 'on-surface-variant', 'outline-variant', 'error']) {
        expect(v[`--md-sys-color-${role}`]).toMatch(/^#[0-9a-f]{6}$/);
      }
    }
    expect(schemeVars('#6750a4', false)['--md-sys-color-surface']).not.toBe(schemeVars('#6750a4', true)['--md-sys-color-surface']);
  });

  it('inlined tokens.css matches the default seed (run with UPDATE_TOKENS=1 to regenerate)', () => {
    const expected = HEADER + themeCss(DEFAULT_SEED) + '\n';
    if (process.env.UPDATE_TOKENS) fs.writeFileSync(TOKENS, expected);
    expect(fs.readFileSync(TOKENS, 'utf8')).toBe(expected);
  });

  it('injects a stylesheet for a custom seed and removes it for the default', async () => {
    await applySeed('#b3261e');
    const el = document.getElementById('m3-dynamic-theme');
    expect(el?.textContent).toContain('--md-sys-color-primary:');
    await applySeed(DEFAULT_SEED);
    expect(document.getElementById('m3-dynamic-theme')).toBeNull();
  });

  it('forces light/dark via data-theme, system clears it', () => {
    applyThemeMode('dark');
    expect(document.documentElement.dataset.theme).toBe('dark');
    applyThemeMode('system');
    expect(document.documentElement.hasAttribute('data-theme')).toBe(false);
  });
});
